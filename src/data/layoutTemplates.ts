export function getLayoutTemplateById(id: string): LayoutTemplate {
  const match = LAYOUT_TEMPLATES.find((t) => t.id === id);
  if (match) return match;

  if (id.startsWith('custom-')) {
    const num = parseInt(id.replace('custom-', ''), 10) || 1;
    const base = LAYOUT_TEMPLATES.find((t) => t.rowCategory === num) || LAYOUT_TEMPLATES[0];
    return {
      ...base,
      id,
      name: `Custom ${num}-Window Grid`,
      type: 'custom-grid',
      isCustomGrid: true,
      boxes: base.boxes.map((b) => ({ ...b })),
    };
  }

  return LAYOUT_TEMPLATES[0];
}
